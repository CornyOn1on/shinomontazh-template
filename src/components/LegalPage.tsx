import type { SiteConfig } from "../types/content";
import { fullAddress } from "../lib/maps";
import { buildTelUrl, displayPhone } from "../lib/maps";
import { normalizeTelegramUsername } from "../lib/booking";

interface LegalPageProps {
  site: SiteConfig;
  onClose: () => void;
}

/**
 * Страница политики конфиденциальности и обработки персональных данных.
 *
 * Открывается как внутренний экран по хэшу #privacy — без серверной
 * маршрутизации, которая на GitHub Pages не работает.
 */
export function LegalPage({ site, onClose }: LegalPageProps) {
  const telUrl = buildTelUrl(site.phone);
  const telegramUsername = normalizeTelegramUsername(site.telegramUsername);

  const contacts = [
    site.companyName,
    fullAddress(site),
    site.phone ? `Телефон: ${displayPhone(site.phone)}` : "",
    telegramUsername ? `Telegram: @${telegramUsername}` : "",
  ].filter(Boolean);

  return (
    <main className="container legal">
      <button type="button" className="legal__back" onClick={onClose}>
        ← Вернуться на сайт
      </button>

      <h1>Политика конфиденциальности и обработка персональных данных</h1>

      <p>
        Этот сайт — статическая страница. У него нет серверной части, базы данных и личного кабинета,
        поэтому данные, которые вы вводите в форму записи, никуда автоматически не отправляются и не
        сохраняются.
      </p>

      <h2>Какие данные используются</h2>
      <p>
        В форме записи вы указываете имя, телефон, услугу и, при желании, комментарий. Эти данные
        нужны только для того, чтобы мастер мог связаться с вами и согласовать время работ.
      </p>

      <h2>Как передаются данные</h2>
      <p>
        Сайт формирует текст заявки и открывает выбранный вами мессенджер — Telegram или MAX. Сообщение
        уходит владельцу только после того, как вы сами нажмёте кнопку отправки в мессенджере. До этого
        момента заявка считается неотправленной.
      </p>
      <p>
        Если вы выбрали вариант «Скопировать заявку», текст попадает только в буфер обмена вашего
        устройства. Куда его отправить — решаете вы.
      </p>

      <h2>Куки и аналитика</h2>
      <p>
        Сайт не устанавливает собственные куки, не ведёт профилирование и не передаёт данные третьим
        лицам. Встроенная карта Яндекс Карт загружается напрямую с серверов Яндекса и может
        использовать собственные технические куки в соответствии с политикой Яндекса.
      </p>

      <h2>Хранение и удаление</h2>
      <p>
        Сайт не хранит ваши данные. Вся переписка остаётся в вашем мессенджере. Чтобы удалить
        отправленное сообщение или задать вопрос об обработке данных, обратитесь к владельцу компании
        по контактам ниже.
      </p>

      <h2>Согласие</h2>
      <p>
        Отмечая чекбокс согласия в форме, вы подтверждаете, что ознакомились с этой политикой и
        согласны на обработку указанных данных для связи по вашей заявке.
      </p>

      <h2>Контакты</h2>
      <ul>
        {contacts.map((line) => (
          <li key={line}>{line}</li>
        ))}
        {telUrl ? (
          <li>
            <a href={telUrl}>Позвонить: {displayPhone(site.phone)}</a>
          </li>
        ) : null}
      </ul>
    </main>
  );
}
